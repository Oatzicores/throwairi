/**
 * Builds the long, ready-to-paste Thai prompt behind each "ลองดู:" chip on the home form.
 *
 * Each idea only stores what is specific to its task (a short keyword, the goal, the details the
 * user fills in, and what the result must contain). The shared structure, quality rules and output
 * format come from the template for its kind, so every prompt reads the same way and tells the AI
 * what to do right away. Everything is Thai on purpose.
 *
 * These are written by the ThrowAirI team. They carry no statistic and no claim about what people
 * search for or how popular a task is (CONTEXT.md, "Trend idea"), and they name no tool or price.
 */

export type IdeaKind = "video" | "image" | "audio" | "code" | "write" | "learn" | "biz" | "agent";

export interface PromptIdea {
  /** Short phrase shown on the chip and used as the search text. Plain Thai, never cryptic. */
  kw: string;
  kind: IdeaKind;
  /** One sentence: what the AI must produce. */
  goal: string;
  /** What the user fills in, written as "ชื่อช่อง: [คำอธิบาย]". */
  info: string[];
  /** What the result must contain (task-specific). */
  need: string[];
  /** Only for ideas backed by a published statistic. Not shown on the page. */
  stat?: string;
  sourceName?: string;
  sourceUrl?: string;
}

export function idea(kind: IdeaKind, kw: string, goal: string, info: string[], need: string[]): PromptIdea {
  return { kw, kind, goal, info, need };
}

