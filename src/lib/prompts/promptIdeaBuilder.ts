export function buildFullPrompt(i: PromptIdea): string {
  const list = (items: string[]) => items.map((x) => `- ${x}`).join("\n");
  return [
    `คุณคือ${ROLE[i.kind]}`,
    `เป้าหมาย: ${i.goal}`,
    `ข้อมูลของฉัน (ฉันจะแทนที่ข้อความในวงเล็บเหลี่ยม [ ] ด้วยข้อมูลจริง ถ้าช่องไหนยังว่าง ให้เลือกค่าที่เหมาะสมที่สุดเอง แล้วบอกว่าเลือกอะไรและเพราะอะไร):\n${list(i.info)}`,
    `สิ่งที่ต้องมีในผลงาน:\n${list(i.need)}`,
    `ข้อกำหนดคุณภาพ:\n${list(QUALITY[i.kind])}`,
    `รูปแบบผลลัพธ์:\n${list(OUTPUT[i.kind])}`,
    "วิธีทำงาน:\n" +
      list([
        "ถ้าขาดข้อมูลสำคัญจริงๆ ให้ถามฉันก่อนไม่เกิน 3 ข้อ ถ้าพอทำได้แล้วให้ลงมือทำทันทีโดยไม่ต้องถามซ้ำ",
        "ตอบเป็นภาษาไทยทั้งหมด ยกเว้นชื่อเฉพาะและศัพท์เทคนิคที่จำเป็น",
        "เมื่อทำเสร็จ เสนอ 2–3 จุดที่ฉันปรับต่อได้เพื่อให้ผลงานดีขึ้น",
      ]),
  ].join("\n\n");
}
